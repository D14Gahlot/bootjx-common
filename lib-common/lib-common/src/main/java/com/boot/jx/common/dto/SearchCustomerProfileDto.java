package com.boot.jx.common.dto;

public class SearchCustomerProfileDto {
	String id;
	String phone;
	String emailId;
	String chatContactId;
	public String getId() {
		return id;
	}
	public void setId(String id) {
		this.id = id;
	}
	public String getPhone() {
		return phone;
	}
	public void setPhone(String phone) {
		this.phone = phone;
	}
	public String getEmailId() {
		return emailId;
	}
	public void setEmailId(String emailId) {
		this.emailId = emailId;
	}
	public String getChatContactId() {
		return chatContactId;
	}
	public void setChatContactId(String chatContactId) {
		this.chatContactId = chatContactId;
	}
	

}
